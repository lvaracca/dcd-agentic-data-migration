-- =============================================================================
-- UrbanFork Snowflake Source Setup — Step 3: Snowflake Orchestrator (7-Task DAG)
-- & Dynamic Tables
--
-- DEMO HIGHLIGHT (Snowflake Tasks -> BigQuery Dataform Migration):
-- Models a realistic 4-tier, 7-node Snowflake Task Graph (DAG) with multi-parent
-- fan-in dependencies + CDC Streams + a Dynamic Table:
--
--                     [TSK_00_ROOT_CDC_ROUTER] (CRON */15 * * * *)
--                        /          |           \
--                       v           v            v
--      [TSK_01A_STAGE_ORDERS] [TSK_01B_PARSE_PINGS] [TSK_01C_STAGE_DISPUTES]
--                 \                 |                 /
--                  +--------+-------+--------+-------+
--                           |                |
--                           v                v
--          [TSK_02A_MART_NET_REVENUE]  [TSK_02B_MART_PRIME_PARTNERS]
--                           \                /
--                            v              v
--                   [TSK_03_REFRESH_PBI_AND_AUDIT]
--
-- Antigravity inspects this entire Snowflake Task Graph and converts it into a
-- Git-versioned Dataform DAG (.sqlx models, assertions & Workflow Config) on GCP!
-- =============================================================================
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE UF_TRANSFORM_WH;
USE DATABASE URBANFORK_PROD;

-- -----------------------------------------------------------------------------
-- 1. CDC Streams on Raw Landing Tables (fed upstream by Airbyte)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE STREAM OPS_RAW.STRM_DLV_ORD_HDR
    ON TABLE OPS_RAW.DLV_ORD_HDR
    SHOW_INITIAL_ROWS = TRUE;

CREATE OR REPLACE STREAM OPS_RAW.STRM_DSP_REFUND_FCT
    ON TABLE OPS_RAW.DSP_REFUND_FCT
    SHOW_INITIAL_ROWS = TRUE;

-- -----------------------------------------------------------------------------
-- 2. Dynamic Table: Live Zone Fleet Supply Deficit (Snapshot Trap Guardrail)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE DYNAMIC TABLE MART.DT_LIVE_ZONE_SUPPLY_DEFICIT
    TARGET_LAG = '15 minutes'
    WAREHOUSE = UF_TRANSFORM_WH
    INITIALIZE = ON_CREATE
AS
SELECT
    s.SNAP_TS AS LATEST_SNAP_TS,
    s.ZONE_ID,
    z.CITY_NM,
    z.CNTRY_CD,
    z.REG_CD,
    s.ONLINE_CRR_N,
    s.BUSY_CRR_N,
    (s.ONLINE_CRR_N - s.BUSY_CRR_N) AS IDLE_CRR_N,
    s.UNASSIGNED_ORD_N,
    ROUND(
        s.UNASSIGNED_ORD_N / NULLIF(GREATEST(s.ONLINE_CRR_N - s.BUSY_CRR_N, 0), 0),
        2
    ) AS SUPPLY_DEFICIT_RATIO
FROM OPS_RAW.ZNE_FLEET_SNAP s
JOIN OPS_RAW.GEO_ZONE_LKP z ON s.ZONE_ID = z.ZONE_ID
QUALIFY RANK() OVER (PARTITION BY s.ZONE_ID ORDER BY s.SNAP_TS DESC) = 1;

ALTER DYNAMIC TABLE MART.DT_LIVE_ZONE_SUPPLY_DEFICIT SUSPEND;

