-- -----------------------------------------------------------------------------
-- 4. Define the 7-Node Snowflake Task DAG (Root -> Tier 1 -> Tier 2 -> Tier 3)
-- -----------------------------------------------------------------------------

-- [ROOT] Tier 0: Cron-scheduled orchestrator gate
CREATE OR REPLACE TASK MART.TSK_00_ROOT_CDC_ROUTER
    WAREHOUSE = UF_TRANSFORM_WH
    SCHEDULE = 'USING CRON 0/15 * * * * UTC'
    COMMENT = 'Root orchestrator task: checks upstream Airbyte CDC streams and triggers staging fan-out'
AS
SELECT CURRENT_TIMESTAMP() AS DAG_TRIGGER_TS;

-- [TIER 1A] Stage Orders & Pre-Aggregate Basket GMV (prevents line-item fan-out)
CREATE OR REPLACE TASK MART.TSK_01A_STAGE_ORDERS
    WAREHOUSE = UF_TRANSFORM_WH
    AFTER MART.TSK_00_ROOT_CDC_ROUTER
AS
INSERT OVERWRITE INTO MART.STG_ORDER_BASKETS
WITH basket AS (
    SELECT
        ORD_ID,
        SUM(QTY_N * UNIT_PRC_USD) AS GMV_USD,
        SUM(QTY_N) AS TOTAL_ITEMS_N
    FROM OPS_RAW.DLV_ORD_ITEM_LN
    GROUP BY ORD_ID
)
SELECT
    h.ORD_ID,
    h.ORD_DT_SK,
    h.ORD_TS,
    TO_DATE(h.ORD_TS) AS ORD_DT,
    h.USR_ID,
    h.MRC_ID,
    h.CRR_ID,
    h.ZONE_ID,
    h.VERT_CD,
    h.ORD_STS_CD,
    COALESCE(b.GMV_USD, 0) AS GMV_USD,
    COALESCE(b.TOTAL_ITEMS_N, 0) AS TOTAL_ITEMS_N,
    h.DLV_FEE_USD,
    h.SRV_FEE_USD,
    h.TIP_USD,
    h.CRR_PAY_USD,
    h.PROMO_VOUCHER_USD
FROM OPS_RAW.DLV_ORD_HDR h
LEFT JOIN basket b ON h.ORD_ID = b.ORD_ID;

-- [TIER 1B] Parse Semi-Structured VARIANT Delivery Pings (excludes 3.8.0-beta GPS bug)
CREATE OR REPLACE TASK MART.TSK_01B_PARSE_PINGS
    WAREHOUSE = UF_TRANSFORM_WH
    AFTER MART.TSK_00_ROOT_CDC_ROUTER
AS
INSERT OVERWRITE INTO MART.STG_CLEAN_DELIVERY_PINGS
SELECT
    p.ORD_ID,
    p.INGEST_TS AS DELIVERED_PING_TS,
    p.PAYLOAD:app_ver::VARCHAR AS APP_VER,
    TRY_TO_NUMBER(p.PAYLOAD:metrics.prep_sec::VARCHAR) AS KITCHEN_PREP_SEC,
    TRY_TO_NUMBER(p.PAYLOAD:metrics.travel_sec::VARCHAR) AS COURIER_TRAVEL_SEC,
    TRY_TO_NUMBER(p.PAYLOAD:metrics.eta_sec::VARCHAR) AS QUOTED_ETA_SEC,
    ARRAY_CONTAINS('SLA_EXCEEDED'::VARIANT, p.PAYLOAD:anomaly_flags) AS HAS_SLA_EXCEEDED_FLAG
FROM IOT_RAW.APP_DELIVERY_PINGS p
WHERE p.PAYLOAD:stage::VARCHAR = 'DELIVERED'
  AND p.PAYLOAD:app_ver::VARCHAR != '3.8.0-beta'
QUALIFY ROW_NUMBER() OVER (PARTITION BY p.ORD_ID ORDER BY p.INGEST_TS DESC) = 1;

-- [TIER 1C] Pre-Aggregate Disputes & Chargebacks ('CBK-' || ORD_ID string join)
CREATE OR REPLACE TASK MART.TSK_01C_STAGE_DISPUTES
    WAREHOUSE = UF_TRANSFORM_WH
    AFTER MART.TSK_00_ROOT_CDC_ROUTER
AS
INSERT OVERWRITE INTO MART.STG_ORDER_DISPUTES_AGG
SELECT
    d.ORD_ID,
    SUM(IFF(d.RFND_STS_FLG = 1, d.RFND_AMT_USD, 0)) AS APPROVED_REFUND_USD,
    COUNT_IF(d.RFND_STS_FLG = 1 AND d.DSP_RSN_CD IN (1, 2)) AS QUALITY_DISPUTE_CNT,
    COUNT(DISTINCT d.DSP_ID) AS TOTAL_DISPUTE_CNT,
    ZEROIFNULL(MAX(ABS(led.LEDGER_AMT_USD))) AS CHARGEBACK_RECOVERED_USD
FROM OPS_RAW.DSP_REFUND_FCT d
LEFT JOIN OPS_RAW.MRC_PAYOUT_LEDGER led
    ON CONCAT('CBK-', d.ORD_ID) = led.REF_DOC_TXT
GROUP BY d.ORD_ID;

-- [TIER 2A] Multi-Parent Fan-In Task: Build Gold Platform Net Revenue Mart (SCD2 Join)
CREATE OR REPLACE TASK MART.TSK_02A_MART_NET_REVENUE
    WAREHOUSE = UF_TRANSFORM_WH
    AFTER MART.TSK_01A_STAGE_ORDERS, MART.TSK_01C_STAGE_DISPUTES
AS
INSERT OVERWRITE INTO MART.FCT_PLATFORM_NET_REVENUE
SELECT
    cal.CAL_DT,
    cal.FISC_YR_N,
    cal.FISC_QTR_N,
    z.REG_CD,
    z.CITY_NM,
    s.ZONE_ID,
    s.VERT_CD,
    IFF(s.VERT_CD = 1, 'Restaurant', 'Grocery') AS VERTICAL_NM,
    COUNT(DISTINCT s.ORD_ID) AS COMPLETED_ORDERS_CNT,
    SUM(s.GMV_USD) AS GROSS_MERCHANDISE_VALUE_USD,
    SUM(ROUND(s.GMV_USD * scd.COMM_RATE_PCT, 2)) AS MERCHANT_COMMISSION_REV_USD,
    SUM(s.DLV_FEE_USD + s.SRV_FEE_USD) AS CUSTOMER_FEES_REV_USD,
    SUM(s.CRR_PAY_USD) AS COURIER_COST_USD,
    SUM(s.PROMO_VOUCHER_USD) AS PROMO_SUBSIDY_USD,
    SUM(ZEROIFNULL(d.APPROVED_REFUND_USD)) AS APPROVED_REFUNDS_USD,
    SUM(
        ROUND(s.GMV_USD * scd.COMM_RATE_PCT, 2)
        + s.DLV_FEE_USD
        + s.SRV_FEE_USD
        - s.CRR_PAY_USD
        - s.PROMO_VOUCHER_USD
        - ZEROIFNULL(d.APPROVED_REFUND_USD)
    ) AS PLATFORM_NET_REVENUE_USD,
    ROUND(
        SUM(
            ROUND(s.GMV_USD * scd.COMM_RATE_PCT, 2)
            + s.DLV_FEE_USD
            + s.SRV_FEE_USD
            - s.CRR_PAY_USD
            - s.PROMO_VOUCHER_USD
            - ZEROIFNULL(d.APPROVED_REFUND_USD)
        ) / NULLIF(SUM(s.GMV_USD), 0),
        4
    ) AS EFFECTIVE_TAKE_RATE_PCT
FROM MART.STG_ORDER_BASKETS s
JOIN OPS_RAW.SYS_CAL_DIM cal ON s.ORD_DT_SK = cal.DT_SK
JOIN OPS_RAW.GEO_ZONE_LKP z ON s.ZONE_ID = z.ZONE_ID
JOIN OPS_RAW.MRC_COMM_SCD2 scd
    ON s.MRC_ID = scd.MRC_ID
   AND cal.CAL_DT BETWEEN scd.EFF_FROM_DT AND scd.EFF_TO_DT
LEFT JOIN MART.STG_ORDER_DISPUTES_AGG d ON s.ORD_ID = d.ORD_ID
WHERE s.ORD_STS_CD = 'D'
GROUP BY 1, 2, 3, 4, 5, 6, 7, 8;

-- [TIER 2B] Multi-Parent Fan-In Task: Build Gold Prime Partner Scorecard
CREATE OR REPLACE TASK MART.TSK_02B_MART_PRIME_PARTNERS
    WAREHOUSE = UF_TRANSFORM_WH
    AFTER MART.TSK_01A_STAGE_ORDERS, MART.TSK_01B_PARSE_PINGS, MART.TSK_01C_STAGE_DISPUTES
AS
INSERT OVERWRITE INTO MART.DIM_PRIME_PARTNER_SCORECARD
WITH anchor AS (
    SELECT MAX(ORD_DT) AS MAX_DT FROM MART.STG_ORDER_BASKETS
),
win90 AS (
    SELECT b.*
    FROM MART.STG_ORDER_BASKETS b
    CROSS JOIN anchor a
    WHERE b.ORD_DT > DATEADD('day', -90, a.MAX_DT)
),
agg AS (
    SELECT
        w.MRC_ID,
        COUNT(*) AS TOTAL_ORD_90D,
        COUNT_IF(w.ORD_STS_CD = 'D') AS DELIV_ORD_90D,
        COUNT_IF(w.ORD_STS_CD = 'R') AS REJ_ORD_90D,
        SUM(IFF(w.ORD_STS_CD = 'D', w.GMV_USD, 0)) AS GMV_90D_USD,
        AVG(IFF(w.ORD_STS_CD = 'D', p.KITCHEN_PREP_SEC / 60.0, NULL)) AS AVG_PREP_MIN_90D,
        COUNT_IF(w.ORD_STS_CD = 'D' AND COALESCE(d.QUALITY_DISPUTE_CNT, 0) > 0) AS QUAL_DISP_ORD_90D,
        SUM(IFF(w.ORD_STS_CD = 'D', COALESCE(d.CHARGEBACK_RECOVERED_USD, 0), 0)) AS CBK_90D_USD
    FROM win90 w
    LEFT JOIN MART.STG_CLEAN_DELIVERY_PINGS p ON w.ORD_ID = p.ORD_ID
    LEFT JOIN MART.STG_ORDER_DISPUTES_AGG d ON w.ORD_ID = d.ORD_ID
    GROUP BY w.MRC_ID
)
SELECT
    m.MRC_ID,
    m.MRC_NM,
    IFF(m.VERT_CD = 1, 'Restaurant', 'Grocery') AS VERTICAL_NM,
    m.CUISINE_CAT,
    z.ZONE_ID,
    z.CITY_NM,
    z.REG_CD,
    ZEROIFNULL(a.GMV_90D_USD) AS TRAILING_90D_GMV_USD,
    ZEROIFNULL(a.DELIV_ORD_90D) AS DELIVERED_ORDERS_90D,
    ROUND(a.AVG_PREP_MIN_90D, 2) AS AVG_PREP_MIN_90D,
    ROUND(ZEROIFNULL(a.QUAL_DISP_ORD_90D) / NULLIF(a.DELIV_ORD_90D, 0), 4) AS QUALITY_DISPUTE_RATE,
    ROUND(ZEROIFNULL(a.REJ_ORD_90D) / NULLIF(a.TOTAL_ORD_90D, 0), 4) AS MERCHANT_REJECTION_RATE,
    ZEROIFNULL(a.CBK_90D_USD) AS CHARGEBACK_DEDUCTIONS_USD,
    IFF(
        ZEROIFNULL(a.GMV_90D_USD) > 25000
        AND a.AVG_PREP_MIN_90D < 14.0
        AND (ZEROIFNULL(a.QUAL_DISP_ORD_90D) / NULLIF(a.DELIV_ORD_90D, 0)) < 0.02
        AND (ZEROIFNULL(a.REJ_ORD_90D) / NULLIF(a.TOTAL_ORD_90D, 0)) < 0.01,
        TRUE,
        FALSE
    ) AS IS_PRIME_PARTNER
FROM OPS_RAW.MRC_PARTNER_MSTR m
JOIN OPS_RAW.GEO_ZONE_LKP z ON m.ZONE_ID = z.ZONE_ID
LEFT JOIN agg a ON m.MRC_ID = a.MRC_ID
WHERE m.ACTIVE_FLG = 1;

-- [TIER 3] Final Fan-In Task: Refresh Power BI Executive Summary & Run Compliance Audit
CREATE OR REPLACE TASK MART.TSK_03_REFRESH_PBI_AND_AUDIT
    WAREHOUSE = UF_TRANSFORM_WH
    AFTER MART.TSK_02A_MART_NET_REVENUE, MART.TSK_02B_MART_PRIME_PARTNERS
AS
EXECUTE IMMEDIATE
$$
BEGIN
    INSERT OVERWRITE INTO MART.RPT_PBI_EXECUTIVE_SUMMARY
    WITH prime_by_reg AS (
        SELECT REG_CD, VERTICAL_NM, COUNT_IF(IS_PRIME_PARTNER) AS PRIME_CNT
        FROM MART.DIM_PRIME_PARTNER_SCORECARD
        GROUP BY 1, 2
    )
    SELECT
        DATE_TRUNC('month', f.CAL_DT) AS REPORT_MONTH,
        f.REG_CD,
        f.VERTICAL_NM,
        SUM(f.COMPLETED_ORDERS_CNT) AS COMPLETED_ORDERS_CNT,
        SUM(f.GROSS_MERCHANDISE_VALUE_USD) AS GMV_USD,
        SUM(f.PLATFORM_NET_REVENUE_USD) AS PLATFORM_NET_REVENUE_USD,
        SUM(f.APPROVED_REFUNDS_USD) AS APPROVED_REFUNDS_USD,
        ROUND(SUM(f.PLATFORM_NET_REVENUE_USD) / NULLIF(SUM(f.GROSS_MERCHANDISE_VALUE_USD), 0), 4) AS EFFECTIVE_TAKE_RATE_PCT,
        ZEROIFNULL(MAX(p.PRIME_CNT)) AS ACTIVE_PRIME_PARTNERS_CNT,
        CURRENT_TIMESTAMP() AS LAST_REFRESHED_UTC
    FROM MART.FCT_PLATFORM_NET_REVENUE f
    LEFT JOIN prime_by_reg p
        ON f.REG_CD = p.REG_CD AND f.VERTICAL_NM = p.VERTICAL_NM
    GROUP BY 1, 2, 3;

    CALL MART.SP_AUDIT_DISPUTE_CHARGEBACKS(500.0);
END;
$$;

-- Resume child tasks bottom-up so the DAG is valid & runnable via EXECUTE TASK,
-- while keeping TSK_00_ROOT_CDC_ROUTER SUSPENDED so cron doesn't burn idle credits!
ALTER TASK MART.TSK_03_REFRESH_PBI_AND_AUDIT RESUME;
ALTER TASK MART.TSK_02A_MART_NET_REVENUE RESUME;
ALTER TASK MART.TSK_02B_MART_PRIME_PARTNERS RESUME;
ALTER TASK MART.TSK_01A_STAGE_ORDERS RESUME;
ALTER TASK MART.TSK_01B_PARSE_PINGS RESUME;
ALTER TASK MART.TSK_01C_STAGE_DISPUTES RESUME;
-- Root remains SUSPENDED until triggered manually via EXECUTE TASK MART.TSK_00_ROOT_CDC_ROUTER!
