USE ROLE ACCOUNTADMIN;
USE WAREHOUSE QB_LOAD_WH;
USE DATABASE QUICKBITE_PROD;

CREATE ROLE IF NOT EXISTS QB_ANALYST_EMEA;
GRANT USAGE ON DATABASE QUICKBITE_PROD TO ROLE QB_ANALYST_EMEA;
GRANT USAGE ON SCHEMA QUICKBITE_PROD.OPS_RAW TO ROLE QB_ANALYST_EMEA;
GRANT USAGE ON SCHEMA QUICKBITE_PROD.MART TO ROLE QB_ANALYST_EMEA;
GRANT SELECT ON ALL TABLES IN SCHEMA QUICKBITE_PROD.OPS_RAW TO ROLE QB_ANALYST_EMEA;
GRANT SELECT ON ALL VIEWS IN SCHEMA QUICKBITE_PROD.MART TO ROLE QB_ANALYST_EMEA;

-- 1. Object Tagging for PII Classification
CREATE OR REPLACE TAG GOVERNANCE.PII_SENSITIVITY
    ALLOWED_VALUES 'PUBLIC', 'CONFIDENTIAL_PII', 'RESTRICTED_CONTACT';

ALTER TABLE OPS_RAW.CUST_USER_MSTR MODIFY
    COLUMN EMAIL_TXT SET TAG GOVERNANCE.PII_SENSITIVITY = 'CONFIDENTIAL_PII',
    COLUMN PHONE_TXT SET TAG GOVERNANCE.PII_SENSITIVITY = 'RESTRICTED_CONTACT';

ALTER TABLE OPS_RAW.CRR_COURIER_MSTR MODIFY
    COLUMN PHONE_TXT SET TAG GOVERNANCE.PII_SENSITIVITY = 'RESTRICTED_CONTACT';

-- 2. Dynamic Data Masking Policies (Email & Phone)
CREATE OR REPLACE MASKING POLICY GOVERNANCE.MSK_EMAIL_POLICY AS (val STRING) RETURNS STRING ->
    CASE
        WHEN IS_ROLE_IN_SESSION('ACCOUNTADMIN') OR IS_ROLE_IN_SESSION('SECURITYADMIN') THEN val
        WHEN val IS NULL THEN NULL
        ELSE CONCAT(LEFT(val, 2), '****@****.com')
    END;

CREATE OR REPLACE MASKING POLICY GOVERNANCE.MSK_PHONE_POLICY AS (val STRING) RETURNS STRING ->
    CASE
        WHEN IS_ROLE_IN_SESSION('ACCOUNTADMIN') OR IS_ROLE_IN_SESSION('SECURITYADMIN') THEN val
        WHEN val IS NULL THEN NULL
        ELSE CONCAT('***-***-', RIGHT(val, 4))
    END;

ALTER TABLE OPS_RAW.CUST_USER_MSTR MODIFY COLUMN EMAIL_TXT SET MASKING POLICY GOVERNANCE.MSK_EMAIL_POLICY;
ALTER TABLE OPS_RAW.CUST_USER_MSTR MODIFY COLUMN PHONE_TXT SET MASKING POLICY GOVERNANCE.MSK_PHONE_POLICY;
ALTER TABLE OPS_RAW.CRR_COURIER_MSTR MODIFY COLUMN PHONE_TXT SET MASKING POLICY GOVERNANCE.MSK_PHONE_POLICY;

-- 3. Regional Row Access Policy on GEO_ZONE_LKP
CREATE OR REPLACE ROW ACCESS POLICY GOVERNANCE.RAP_REGIONAL_ZONE_ACCESS AS (reg_val VARCHAR) RETURNS BOOLEAN ->
    CASE
        WHEN IS_ROLE_IN_SESSION('ACCOUNTADMIN') OR IS_ROLE_IN_SESSION('SECURITYADMIN') THEN TRUE
        WHEN IS_ROLE_IN_SESSION('QB_ANALYST_EMEA') AND reg_val = 'EMEA' THEN TRUE
        WHEN IS_ROLE_IN_SESSION('QB_ANALYST_AMER') AND reg_val = 'AMER' THEN TRUE
        WHEN IS_ROLE_IN_SESSION('QB_ANALYST_APAC') AND reg_val = 'APAC' THEN TRUE
        ELSE FALSE
    END;

ALTER TABLE OPS_RAW.GEO_ZONE_LKP
    ADD ROW ACCESS POLICY GOVERNANCE.RAP_REGIONAL_ZONE_ACCESS ON (REG_CD);
